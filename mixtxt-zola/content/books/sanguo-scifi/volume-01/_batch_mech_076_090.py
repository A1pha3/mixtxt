def apply(text):
    for old, new in REPL:
        if old in text:
            text = text.replace(old, new)
    return text

total = 0
for fn in FILES:
    p = os.path.join(VOL, fn)
    if not os.path.exists(p):
        continue
    with open(p, encoding="utf-8") as f:
        t = f.read()
    hits = sum(t.count(o) for o, _ in REPL if o)
    t2 = apply(t)
    with open(p, "w", encoding="utf-8") as f:
        f.write(t2)
    total += hits
    print(f"[OK] {fn}: 机制命中约 {hits} 处")

print(f"\n合计机制层命中约 {total} 处")
